package com.brandon3055.draconicevolution.config;

import com.brandon3055.brandonscore.registry.ModConfigContainer;
import com.brandon3055.brandonscore.registry.ModConfigProperty;
import com.brandon3055.draconicevolution.DraconicEvolution;

/** Config category "World". World generation options. */
@ModConfigContainer(modid = DraconicEvolution.MODID)
public final class WorldConfig {

    @ModConfigProperty(
            category = "World",
            name = "worldGenEnabled",
            comment = "Setting this to false will just completely disable ALL DE world gen!")
    public static boolean worldGenEnabled = true;

    @ModConfigProperty(
            category = "World",
            name = "enableRetroGen",
            comment =
                    "Set this to false if you do not want ore added to chunks that have not previously been generated by DE (this can almost always be left true).")
    public static boolean enableRetroGen = true;

    @ModConfigProperty(
            category = "World",
            name = "disableOreSpawnOverworld",
            comment = "Disables draconium ore generation in the overworld.")
    public static boolean disableOreSpawnOverworld = false;

    @ModConfigProperty(
            category = "World",
            name = "disableOreSpawnEnd",
            comment = "Disables draconium ore generation in the end.")
    public static boolean disableOreSpawnEnd = false;

    @ModConfigProperty(
            category = "World",
            name = "disableOreSpawnNether",
            comment = "Disables draconium ore generation in the nether.")
    public static boolean disableOreSpawnNether = false;

    @ModConfigProperty(
            category = "World",
            name = "generateEnderComets",
            comment = "Set to false to disable the generation of Ender Comets.")
    public static boolean generateEnderComets = true;

    @ModConfigProperty(
            category = "World",
            name = "generateChaosIslands",
            comment = "Set to false to disable the generation of Chaos Islands.")
    public static boolean generateChaosIslands = true;

    @ModConfigProperty(
            category = "World",
            name = "chaosIslandVoidMode",
            comment =
                    "If true, the Chaos Guardian, Crystals, and Healing Crystals will still spawn, but NO other blocks will be placed. (This only exists because someone wanted it for some reason).")
    public static boolean chaosIslandVoidMode = false;

    @ModConfigProperty(
            category = "World",
            name = "cometRarity",
            comment = "Ender Comets have a 1 in {this number} chance to spawn in each chunk.")
    @ModConfigProperty.MinMax(min = "500", max = "1000000")
    public static int cometRarity = 10000;

    @ModConfigProperty(
            category = "World",
            name = "chaosIslandSeparation",
            comment = "This is the distance between Chaos Islands.")
    @ModConfigProperty.MinMax(min = "500", max = "1000000")
    public static int chaosIslandSeparation = 10000;

    @ModConfigProperty(
            category = "World",
            name = "chaosIslandYOffset",
            comment = "This allows you to offset the y position of Chaos Islands.")
    @ModConfigProperty.MinMax(min = "-50", max = "150")
    public static int chaosIslandYOffset = 0;

    // TODO Fix typo in 1.13 [Dimention -> Dimension] (Not going to bother with it now because it
    // would only break existing configs)
    @ModConfigProperty(
            category = "World",
            name = "oreGenDimentionBlacklist",
            comment =
                    "Add the ID of any mod's dimensions that you don't want Draconium Ore generated in.")
    public static int[] oreGenDimentionBlacklist = new int[0];

    private WorldConfig() {}
}
